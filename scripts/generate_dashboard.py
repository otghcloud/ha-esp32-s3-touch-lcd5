#!/usr/bin/env python3
"""Generate the fixed LVGL slots configured at runtime by Home Assistant."""

import argparse
import colorsys
import json
import math
from pathlib import Path
import re
import struct
from urllib.request import urlopen
import zlib

import yaml

from dashboard_pages import buttons, homepage, light_detail, navigation, screensaver, settings, update
from dashboard_pages.shared import MAX_PAGES, chrome, dots, label


ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "esphome" / "dashboard.yaml"
ICON_DATA = ROOT / "scripts" / "mdi-icons.json"
ICON_HEADER = ROOT / "esphome" / "components" / "wallpanel" / "mdi_icons.h"
WHEEL_OUTPUT = ROOT / "assets" / "light_colour_wheel.png"
MDI_VERSION = "7.4.47"
MDI_SOURCE = f"https://cdn.jsdelivr.net/npm/@mdi/font@{MDI_VERSION}"


def load_icons():
    return json.loads(ICON_DATA.read_text(encoding="utf-8"))


def update_icons():
    with urlopen(f"{MDI_SOURCE}/css/materialdesignicons.css", timeout=60) as response:
        css = response.read().decode("utf-8")
    icons = dict(re.findall(r'\.mdi-([\w-]+)::before\s*\{\s*content: "\\([0-9A-F]+)";\s*\}', css))
    if not icons:
        raise ValueError("No MDI icons found in upstream stylesheet")
    ICON_DATA.write_text(json.dumps(icons, sort_keys=True, indent=2) + "\n", encoding="utf-8")


def render_icons():
    entries = []
    for name, codepoint in sorted(load_icons().items()):
        glyph = "".join(f"\\x{byte:02x}" for byte in chr(int(codepoint, 16)).encode("utf-8"))
        entries.append(f'  {{"{name}", "{glyph}"}},')
    return "\n".join([
        f"// Generated by scripts/generate_dashboard.py from MDI {MDI_VERSION}; see MDI-LICENSE.",
        "#pragma once", "#include <algorithm>", "#include <iterator>", "#include <string>",
        "namespace wallpanel {", "struct MdiIcon { const char *name; const char *glyph; };",
        "inline const MdiIcon MDI_ICONS[] = {", *entries, "};",
        "inline const char *mdi_glyph(const std::string &icon) {",
        '  if (icon.compare(0, 4, "mdi:") != 0)',
        "    return nullptr;",
        "  const auto name = icon.substr(4);",
        "  const auto found = std::lower_bound(std::begin(MDI_ICONS), std::end(MDI_ICONS), name,",
        "      [](const MdiIcon &entry, const std::string &value) { return entry.name < value; });",
        "  return found != std::end(MDI_ICONS) && name == found->name ? found->glyph : nullptr;",
        "}", "}  // namespace wallpanel", "",
    ])


