        "id(dashboard).bind_fonts(id(font_icons)->get_lv_font(), id(font_dense_icons)->get_lv_font(), "
        "id(font_medium)->get_lv_font(), id(font_small)->get_lv_font(), id(font_ui_icons)->get_lv_font());",
