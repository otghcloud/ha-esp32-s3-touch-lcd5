#!/usr/bin/env python3
"""Generate the fixed LVGL slots configured at runtime by Home Assistant."""

import argparse
import json
from pathlib import Path
import re
from urllib.request import urlopen

import yaml


ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "esphome" / "dashboard.yaml"
ICON_DATA = ROOT / "scripts" / "mdi-icons.json"
ICON_HEADER = ROOT / "esphome" / "components" / "wallpanel" / "mdi_icons.h"
MDI_VERSION = "7.4.47"
MDI_SOURCE = f"https://cdn.jsdelivr.net/npm/@mdi/font@{MDI_VERSION}"


def load_icons():
    return json.loads(ICON_DATA.read_text(encoding="utf-8"))


def update_icons():
    with urlopen(f"{MDI_SOURCE}/css/materialdesignicons.css", timeout=60) as response:
        css = response.read().decode("utf-8")
    icons = dict(re.findall(r'\.mdi-([\w-]+)::before\s*\{\s*content: "\\([0-9A-F]+)";\s*\}', css))
    if not icons:
        raise ValueError("No MDI icons found in upstream stylesheet")
    ICON_DATA.write_text(json.dumps(icons, sort_keys=True, indent=2) + "\n", encoding="utf-8")


def render_icons():
    entries = []
    for name, codepoint in sorted(load_icons().items()):
        glyph = "".join(f"\\x{byte:02x}" for byte in chr(int(codepoint, 16)).encode("utf-8"))
        entries.append(f'  {{"{name}", "{glyph}"}},')
    return "\n".join([
        f"// Generated by scripts/generate_dashboard.py from MDI {MDI_VERSION}; see MDI-LICENSE.",
        "#pragma once", "#include <algorithm>", "#include <iterator>", "#include <string>",
        "namespace wallpanel {", "struct MdiIcon { const char *name; const char *glyph; };",
        "inline const MdiIcon MDI_ICONS[] = {", *entries, "};",
        "inline const char *mdi_glyph(const std::string &icon) {",
        '  if (icon.compare(0, 4, "mdi:") != 0)',
        "    return nullptr;",
        "  const auto name = icon.substr(4);",
        "  const auto found = std::lower_bound(std::begin(MDI_ICONS), std::end(MDI_ICONS), name,",
        "      [](const MdiIcon &entry, const std::string &value) { return entry.name < value; });",
        "  return found != std::end(MDI_ICONS) && name == found->name ? found->glyph : nullptr;",
        "}", "}  // namespace wallpanel", "",
    ])


def label(widget_id, text, font, **properties):
    return {"label": {"id": widget_id, "text": text, "text_font": font,
                      "text_color": 0xF2F4F8, **properties}}


def make_dashboard():
    widgets = []
    bindings = []
    for p in range(4):
        children = [
            label(f"title_{p}", "", "font_medium", x=24, y=10),
            label(f"temperature_{p}", "", "font_small", align="BOTTOM_LEFT", x=24, y=-14),
        ]
        button_bindings = []
        for b in range(4):
            prefix = f"button_{p}_{b}"
            children.append({"button": {
                "id": prefix, "x": 20 if b % 2 == 0 else 420,
                "y": 65 if b < 2 else 230, "width": 360, "height": 155,
                "bg_color": 0x171F2C, "bg_opa": "90%", "border_color": 0x344154,
                "border_width": 1, "radius": 18, "scrollable": False,
                "widgets": [
                    label(f"{prefix}_icon", "\U000F0335", "font_icons",
                          x=22, y=42, width=72, height=72, text_align="CENTER",
                          text_color=0xF2C66D),
                    label(f"{prefix}_name", "", "font_medium", x=112, y=30,
                          width=220, long_mode="DOT"),
                    label(f"{prefix}_state", "UNKNOWN", "font_medium", x=112, y=78,
                          text_color=0xAAB4C5),
                    label(f"{prefix}_unavailable", "UNAVAILABLE", "font_small",
                          align="TOP_RIGHT", x=-14, y=10, text_color=0xF2A65A),
                ],
            }})
            button_bindings.append(
                "{" + ", ".join(f"id({prefix}{suffix})" for suffix in
                                 ("", "_name", "_state", "_unavailable", "_icon")) + "}"
            )
        for d in range(4):
            children.append({"obj": {
                "id": f"dot_{p}_{d}", "x": 364 + d * 20, "align": "BOTTOM_LEFT",
                "y": -14, "width": 12, "height": 12, "radius": 6,
                "pad_all": 0, "border_width": 2, "border_color": 0xB9C2D0,
                "bg_color": 0xB9C2D0, "bg_opa": "TRANSP",
                "clickable": False, "scrollable": False,
            }})
        widgets.append({"obj": {
            "id": f"page_{p}", "width": 800, "height": 480, "x": 0, "y": 0,
            "pad_all": 0, "border_width": 0, "bg_color": 0x111827, "bg_opa": "COVER",
            "scrollable": False, "hidden": True, "widgets": children,
        }})
        dots = ", ".join(f"id(dot_{p}_{d})" for d in range(4))
        bindings.append(
            f"id(dashboard).bind_page({p}, "
            + "{"
            + f"id(page_{p}), id(title_{p}), id(temperature_{p}), "
            + "{" + dots + "}, {{" + ", ".join(button_bindings) + "}}});"
        )
    widgets.append(label("dashboard_waiting", "Waiting for Home Assistant", "font_medium",
                         align="CENTER"))
    bindings.append(
        "id(dashboard).initialize(id(dashboard_waiting), id(dashboard_connection));"
    )
    return {
        "esphome": {"on_boot": {"priority": -100, "then": [{"lambda": "\n".join(bindings)}]}},
        "font": [{"file": "gfonts://Roboto", "id": name, "size": size}
                 for name, size in (("font_large", 38), ("font_medium", 24), ("font_small", 16))]
                + [{"file": f"{MDI_SOURCE}/fonts/materialdesignicons-webfont.ttf",
                    "id": "font_icons", "size": 72, "bpp": 1, "glyphsets": [],
                    "glyphs": [chr(codepoint) for codepoint in
                               sorted({int(value, 16) for value in load_icons().values()})]}],
        "lvgl": {
            "bg_color": 0x111827, "pad_all": 0, "scrollable": False,
            "top_layer": {"widgets": [
                label("lbl_time", "--:--", "font_large", align="TOP_RIGHT", x=-24, y=4),
                label("dashboard_connection", "HOME ASSISTANT UNAVAILABLE", "font_small",
                      align="BOTTOM_RIGHT", x=-24, y=-36, text_color=0xF2A65A, hidden=True),
            ]},
            "widgets": widgets,
        },
    }


def render():
    return "# Generated by scripts/generate_dashboard.py; edit the generator, not this file.\n" + yaml.safe_dump(
        make_dashboard(), sort_keys=False, width=100
    )


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--update-icons", action="store_true",
                        help="Refresh the pinned MDI name/codepoint catalogue from upstream")
    args = parser.parse_args()
    if args.update_icons:
        if args.check:
            parser.error("--check cannot be combined with --update-icons")
        update_icons()
    for path, content in ((OUTPUT, render()), (ICON_HEADER, render_icons())):
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                parser.error(f"{path.name} is stale; run python3 scripts/generate_dashboard.py")
        else:
            path.write_text(content, encoding="utf-8")


if __name__ == "__main__":
    main()
